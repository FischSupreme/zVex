-- Locate an externally spawned custom avatar model ONLY when its ownership
-- is explicitly linked to a Player. Player.Character itself already supports
-- nested custom MeshParts / accessory models automatically via Highlight.
local function refreshLinkedModels()
    local byName={}
    for _,p in ipairs(Players:GetPlayers()) do
        if p~=LP then byName[p.Name]=p; byName[tostring(p.UserId)]=p end
    end
    local found={}
    for _,obj in ipairs(workspace:GetDescendants()) do
        if obj:IsA("Model") and obj:FindFirstChildWhichIsA("BasePart",true) then
            local owner
            for _,key in ipairs({"PlayerUserId","OwnerUserId","UserId","PlayerId","OwnerId","PlayerName","OwnerName","Username"}) do
                local val=obj:GetAttribute(key)
                if val~=nil then owner=byName[tostring(val)] end
                if owner then break end
            end
            if owner and obj~=owner.Character
                and not (owner.Character and obj:IsDescendantOf(owner.Character)) then
                found[owner.UserId]=obj
            end
        end
    end
    linkedModels=found
    for player,data in pairs(visuals) do
        local linked=found[player.UserId]
        if data.LinkedModel~=linked then
            if data.LinkedHighlight then data.LinkedHighlight:Destroy() end
            data.LinkedHighlight=nil
            data.LinkedModel=linked
            if linked then
                data.LinkedHighlight=new("Highlight",{
                    Adornee=linked,DepthMode=Enum.HighlightDepthMode.AlwaysOnTop,
                    OutlineTransparency=0,FillTransparency=0.7,Enabled=false,
                },root)
            end
        end
    end
end

local function sameTeam(player)
    -- Manual exclusions always apply, even when Team Check is off.
    if ignoredPlayers[player.UserId] then return true end
    if not cfg.TeamCheck then return false end
    -- Roblox Teams: use Team first, then TeamColor if non-neutral.
    if LP.Team ~= nil and player.Team ~= nil and LP.Team == player.Team then
        return true
    end
    if not LP.Neutral and not player.Neutral and LP.TeamColor == player.TeamColor then
        return true
    end
    -- Some custom games publish a faction/team as an attribute.
    local keys={"TeamId","TeamID","TeamName","Faction","Squad","Side"}
    for _,key in ipairs(keys) do
        local localValue=LP:GetAttribute(key)
        local otherValue=player:GetAttribute(key)
        if localValue~=nil and otherValue~=nil and localValue==otherValue then
            return true
        end
    end
    return false
end
local function aimPosition(part,character,camera)
    local position=part.Position
    if cfg.Prediction and cfg.LeadTime>0 then
        local root=character:FindFirstChild("HumanoidRootPart") or part
        local velocity=root.AssemblyLinearVelocity
        -- Clamp lead time and displacement to avoid extreme camera jumps.
        local lead=math.clamp(cfg.LeadTime,0,0.5)
        local offset=velocity*lead
        if offset.Magnitude>35 then offset=offset.Unit*35 end
        position=position+offset
    end
    return position
end
local function getPart(character)
    if cfg.AimPart=="UpperTorso" then
        return character:FindFirstChild("UpperTorso") or character:FindFirstChild("Torso")
            or character:FindFirstChild("HumanoidRootPart")
    end
    return character:FindFirstChild(cfg.AimPart)
        or character:FindFirstChild("Head")
        or character:FindFirstChild("HumanoidRootPart")
end
local function canSee(camera,character,part)
    if cfg.ThroughWalls then return true end
    local origin=camera.CFrame.Position
    local params=RaycastParams.new()
    params.FilterType=Enum.RaycastFilterType.Exclude
    params.FilterDescendantsInstances=LP.Character and {LP.Character} or {}
    local hit=workspace:Raycast(origin,part.Position-origin,params)
    return hit==nil or hit.Instance:IsDescendantOf(character)
end
viewportMouse = function(camera)
    if cfg.FollowCursor then
        -- IgnoreGuiInset=true aligns GUI and WorldToViewportPoint.
        return UIS:GetMouseLocation()
    end
    return camera.ViewportSize/2
end
local function targetClosestToCursor(camera,center)
    local bestPart=nil
    local bestDistance=cfg.FOV
    local bestPlayer=nil
    for _,player in ipairs(Players:GetPlayers()) do
        if player~=LP and not sameTeam(player) then
            local character=player.Character
            local human=character and character:FindFirstChildOfClass("Humanoid")
            if human and human.Health>0 then
                local part=getPart(character)
                if part then
                    local screen,onScreen=camera:WorldToViewportPoint(aimPosition(part,character,camera))
                    if onScreen and screen.Z>0 then
                        local dist=(Vector2.new(screen.X,screen.Y)-center).Magnitude
                        if dist<=bestDistance and canSee(camera,character,part) then
                            bestDistance=dist
                            bestPart=part
                            bestPlayer=player
                        end
                    end
                end
            end
        end
    end
    return bestPart,bestPlayer
end

