local ZVEX_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
local function zvexCheckKey(raw)
    local key = string.upper((raw or ""):gsub("%s+", ""))
    if #key ~= 13 or key:find("[^A-Z0-9]") then return false end
    local acc = 0
    for i = 1, 10 do
        local value = ZVEX_ALPHABET:find(key:sub(i,i), 1, true)
        if not value then return false end
        acc = (acc * 131 + (value - 1) * 17 + i * 7) % 46656
    end
    local check = ""
    for _ = 1, 3 do
        local digit = acc % 36
        check = ZVEX_ALPHABET:sub(digit + 1, digit + 1) .. check
        acc = math.floor(acc / 36)
    end
    return key:sub(11) == check
end

