    end
    local function adjust(x)
        local fraction=math.clamp((x-bar.AbsolutePosition.X)/math.max(bar.AbsoluteSize.X,1),0,1)
        local raw=min+fraction*(max-min)
        cfg[key]=math.clamp(math.floor(raw/step+0.5)*step,min,max)
        refresh()
    end
