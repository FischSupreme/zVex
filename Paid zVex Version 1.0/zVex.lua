local function normalName(value)
    return string.lower(string.gsub(value,"[^%w]",""))
end
local function isNumericValue(obj)
    return obj:IsA("NumberValue") or obj:IsA("IntValue")
end
local function gunControlForName(value)
    local name=normalName(value)
    if recoilNames[name] then return "NoRecoil" end
    if ammoNames[name] then return "InfiniteAmmo" end
    return nil
end
local function desiredGunValue(flag)
    return flag=="NoRecoil" and 0 or 9999
end
local function modifyLocalValue(obj, flag)
    if not isNumericValue(obj) then return false end
    local target=desiredGunValue(flag)
    if originalValues[obj]==nil then
        originalValues[obj]={value=obj.Value,flag=flag}
    end
    local ok=pcall(function() obj.Value=target end)
    return ok
end
local function modifyLocalAttribute(obj,name,flag)
    local current=obj:GetAttribute(name)
    if type(current)~="number" then return false end
    if not originalAttributes[obj] then originalAttributes[obj]={} end
    if originalAttributes[obj][name]==nil then
        originalAttributes[obj][name]={value=current,flag=flag}
    end
    local ok=pcall(function() obj:SetAttribute(name,desiredGunValue(flag)) end)
    return ok
end
local function restoreGunValues(flag)
    for obj,snapshot in pairs(originalValues) do
        if not flag or snapshot.flag==flag then
            pcall(function() obj.Value=snapshot.value end)
            originalValues[obj]=nil
        end
    end
    for obj,attributes in pairs(originalAttributes) do
        for name,snapshot in pairs(attributes) do
            if not flag or snapshot.flag==flag then
                pcall(function() obj:SetAttribute(name,snapshot.value) end)
                attributes[name]=nil
            end
        end
        if next(attributes)==nil then originalAttributes[obj]=nil end
    end
end
local lastNoRecoil=false
local lastInfiniteAmmo=false
local gunUpdateClock=0
local function updateLocalGun(dt)
    if lastNoRecoil and not cfg.NoRecoil then restoreGunValues("NoRecoil") end
    if lastInfiniteAmmo and not cfg.InfiniteAmmo then restoreGunValues("InfiniteAmmo") end
    lastNoRecoil=cfg.NoRecoil
    lastInfiniteAmmo=cfg.InfiniteAmmo

    gunUpdateClock=gunUpdateClock+dt
    if gunUpdateClock<0.18 then return end
    gunUpdateClock=0

    local character=LP.Character
    local tool=character and character:FindFirstChildOfClass("Tool")
    if not tool then
        gunStatus.Text="No weapon equipped"
        return
    end
    local matchedRecoil=0
    local matchedAmmo=0
    local elements={tool}
    for _,child in ipairs(tool:GetDescendants()) do
        table.insert(elements,child)
    end
    for _,obj in ipairs(elements) do
        if isNumericValue(obj) then
            local flag=gunControlForName(obj.Name)
            if flag=="NoRecoil" then
                matchedRecoil=matchedRecoil+1
            elseif flag=="InfiniteAmmo" then
                matchedAmmo=matchedAmmo+1
            end
            if flag and cfg[flag] then modifyLocalValue(obj,flag) end
        end
        for name,value in pairs(obj:GetAttributes()) do
            if type(value)=="number" then
                local flag=gunControlForName(name)
                if flag=="NoRecoil" then
                    matchedRecoil=matchedRecoil+1
                elseif flag=="InfiniteAmmo" then
                    matchedAmmo=matchedAmmo+1
                end
                if flag and cfg[flag] then modifyLocalAttribute(obj,name,flag) end
            end
        end
    end
    gunStatus.Text=tool.Name.."\nLocal fields found: "..
        matchedRecoil.." recoil / "..matchedAmmo.." ammo"
end

-- SCREEN RECOIL STABILIZER
-- Unlike Tool-value editing, this monitors the camera pitch after the
-- usual camera and aim updates and counter-rotates upwards firing kick.
-- Not guaranteed for every custom camera; does not modify server behavior.
local firingMouse = false
local lastShot = -100
local watchedTool = nil
local toolActivationConnection = nil
local priorPitch = nil
local priorCamera = nil
local function equippedTool()
    local char = LP.Character
    return char and char:FindFirstChildOfClass("Tool") or nil
end
local function watchEquippedTool()
    local tool = equippedTool()
    if tool == watchedTool then return tool end
    if toolActivationConnection then
        toolActivationConnection:Disconnect()
        toolActivationConnection = nil
    end
    watchedTool = tool
    priorPitch = nil
    if tool then
        toolActivationConnection = tool.Activated:Connect(function()
            lastShot = os.clock()
        end)
    end
    return tool
end
connect(UIS.InputBegan, function(input, processed)
    if input.UserInputType == Enum.UserInputType.MouseButton1 and not processed then
        firingMouse = true
        if equippedTool() then lastShot = os.clock() end
    end
end)
connect(UIS.InputEnded, function(input)
    if input.UserInputType == Enum.UserInputType.MouseButton1 then
        firingMouse = false
    end
end)
-- Repeated Tool activation for weapons that use the Roblox Tool API.
-- This respects a game's actual fire-rate/ammo rules; custom weapon systems
-- and server-side rate limits may ignore extra activation attempts.
local spamClock = 0
local spamTool = nil
connect(RunService.Heartbeat, function(dt)
    if not active or not cfg.SpamShoot then
        spamClock = 0
        spamTool = nil
        return
    end
    local tool = equippedTool()
    if not tool or not UIS:IsMouseButtonPressed(Enum.UserInputType.MouseButton1)
        or UIS:GetFocusedTextBox() then
        spamClock = 0
        spamTool = nil
        return
    end
    if tool ~= spamTool then
        spamTool = tool
        spamClock = 0
    end
    local interval = 1 / math.max(2, cfg.SpamRate)
    spamClock = spamClock + math.min(dt, 0.1)
    if spamClock >= interval then
        spamClock = spamClock % interval
        pcall(function()
            tool:Deactivate()
            tool:Activate()
        end)
    end
end)

local recoilBinding = "RETRAC_V25_SCREEN_RECOIL"
RunService:BindToRenderStep(recoilBinding, Enum.RenderPriority.Camera.Value + 110, function()
    if not active then return end
    local camera = workspace.CurrentCamera
    if not camera then priorPitch = nil return end
    local tool = watchEquippedTool()
    local pitch = math.asin(math.clamp(camera.CFrame.LookVector.Y, -1, 1))
    if camera ~= priorCamera then
        priorCamera = camera
        priorPitch = pitch
        return
    end
    if not cfg.NoRecoil or not tool or not priorPitch then
        priorPitch = pitch
        return
    end
    local sinceShot = os.clock() - lastShot
    local firing = firingMouse or sinceShot < 0.22
    if firing then
        local upward = pitch - priorPitch
        if upward > 0.0002 then
            -- Limit any one-frame correction to avoid massive jumps.
            local strength = math.clamp(cfg.RecoilStrength / 100, 0, 1)
            local compensation = math.min(upward, math.rad(9)) * strength
            camera.CFrame = camera.CFrame * CFrame.Angles(-compensation, 0, 0)
            pitch = math.asin(math.clamp(camera.CFrame.LookVector.Y, -1, 1))
        end
    end
    priorPitch = pitch
end)

