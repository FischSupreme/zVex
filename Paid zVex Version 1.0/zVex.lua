local originalValues=setmetatable({}, {__mode="k"})
local originalAttributes=setmetatable({}, {__mode="k"})
local recoilNames={
    recoil=true,recoilamount=true,recoilstrength=true,
    verticalrecoil=true,horizontalrecoil=true,recoilx=true,recoily=true,
    kickback=true,camerakick=true,gunrecoil=true,recoilvertical=true,
