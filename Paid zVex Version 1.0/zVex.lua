local function availableSpectatePlayers()
    local result = {}
    for _, player in ipairs(Players:GetPlayers()) do
        if player ~= LP then table.insert(result, player) end
    end
    table.sort(result, function(a,b) return a.Name:lower() < b.Name:lower() end)
    return result
end
local function applySpectate()
    local camera = workspace.CurrentCamera
    if not camera or not spectateTarget then return end
    local character = spectateTarget.Character
    local humanoid = character and character:FindFirstChildOfClass("Humanoid")
    if humanoid then
        -- Scriptable camera prevents the Roblox camera controller from
        -- alternating between your character and the spectated character.
        camera.CameraType = Enum.CameraType.Scriptable
    end
end
local function stopSpectate()
    spectateTarget = nil
    local camera = workspace.CurrentCamera
    local human = LP.Character and LP.Character:FindFirstChildOfClass("Humanoid")
    if camera then
        camera.CameraType = Enum.CameraType.Custom
        if human then camera.CameraSubject = human end
    end
