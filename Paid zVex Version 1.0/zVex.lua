-- Mouse-look differs across games and executors. Before moving the camera
-- toward a player, test each mouse axis and observe the target on screen.
-- A positive test pulse that moves the target left means positive X is
-- the correct input direction for a target to the right (and vice versa).
local aimControl = {
    player = nil,
    phase = "x",   -- probe X, then Y, then track
    pending = nil,
    signX = 1,
    signY = 1,
    failed = false,
    status = "",
}
local function resetAimControl()
    aimControl.player=nil
    aimControl.phase="x"
    aimControl.pending=nil
    aimControl.signX=1
    aimControl.signY=1
    aimControl.failed=false
    aimControl.status=""
end

