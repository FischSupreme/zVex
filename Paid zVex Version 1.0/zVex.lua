-- Returns true once the small empirical direction test is complete.
-- If the executor accepts mouse input but the camera doesn't react,
-- switch to Roblox camera CFrame rather than endlessly steering away.
local function calibrateInput(mouseMove,point)
    if not cfg.AutoCalibrate then
        aimControl.signX=1
        aimControl.signY=1
        aimControl.phase="done"
        return true
    end
    local pending=aimControl.pending
    if pending then
        pending.frames=pending.frames+1
        if pending.frames<2 then return false end
        local now=pending.axis=="x" and point.X or point.Y
        local movement=now-pending.before
        if math.abs(movement)>=0.8 then
            local sign=movement<0 and 1 or -1
            if pending.axis=="x" then
                aimControl.signX=sign
                aimControl.phase="y"
            else
                aimControl.signY=sign
                aimControl.phase="done"
            end
        elseif pending.attempts<2 then
            local success=pcall(mouseMove,
                pending.axis=="x" and 9 or 0,
                pending.axis=="y" and 9 or 0)
            if not success then
                aimControl.failed=true
                return true
            end
            aimControl.pending={
                axis=pending.axis,before=now,frames=0,
                attempts=pending.attempts+1
            }
            return false
        else
            aimControl.failed=true
            return true
        end
        aimControl.pending=nil
        return aimControl.phase=="done"
    end
    if aimControl.phase=="done" then return true end
    local axis=aimControl.phase
    local before=axis=="x" and point.X or point.Y
    local ok=pcall(mouseMove,
        axis=="x" and 9 or 0,
        axis=="y" and 9 or 0)
    if not ok then
        aimControl.failed=true
        return true
    end
    aimControl.pending={axis=axis,before=before,frames=0,attempts=1}
    return false
end

local originalFOVByCamera = setmetatable({}, {__mode="k"})
local function updateCameraFOV(camera)
    if cfg.CameraFOVEnabled then
        if originalFOVByCamera[camera] == nil then
            originalFOVByCamera[camera] = camera.FieldOfView
        end
        local selected = math.clamp(cfg.CameraFOV, 40, 120)
        if math.abs(camera.FieldOfView - selected) > 0.01 then
            camera.FieldOfView = selected
        end
    elseif originalFOVByCamera[camera] ~= nil then
        camera.FieldOfView = originalFOVByCamera[camera]
        originalFOVByCamera[camera] = nil
    end
end

-- Character spin: rotate the local avatar independently from the view.
-- This is client-side and other players seeing it depends on Roblox replication.
-- Keep this separate from the aim/spectate camera code.
local spinBinding = "RETRAC_V30_SPIN"
local spinHumanoid = nil
local previousAutoRotate = nil
local spinAngle = nil

local function releaseSpin()
    if spinHumanoid and spinHumanoid.Parent and previousAutoRotate ~= nil then
        pcall(function() spinHumanoid.AutoRotate = previousAutoRotate end)
    end
    spinHumanoid = nil
    previousAutoRotate = nil
    spinAngle = nil
end

RunService:BindToRenderStep(spinBinding, Enum.RenderPriority.Camera.Value + 80, function(dt)
    if not active or not cfg.Spin or spectateTarget then
        if spinHumanoid then releaseSpin() end
        return
    end
    local character = LP.Character
    local human = character and character:FindFirstChildOfClass("Humanoid")
    local rootPart = character and character:FindFirstChild("HumanoidRootPart")
    if not human or not rootPart or human.Health <= 0 then
        if spinHumanoid then releaseSpin() end
        return
    end
    if human ~= spinHumanoid then
        releaseSpin()
        spinHumanoid = human
        previousAutoRotate = human.AutoRotate
        spinAngle = math.atan2(-rootPart.CFrame.LookVector.X, -rootPart.CFrame.LookVector.Z)
    end
    human.AutoRotate = false
    spinAngle = (spinAngle + math.rad(cfg.SpinSpeed) * math.clamp(dt, 0, 0.1)) % (2 * math.pi)

    local camera = workspace.CurrentCamera
    -- Cache view before character rotation; keep the existing camera view
    -- rather than intentionally spinning the player's first-person viewpoint.
    local cameraCF = camera and camera.CFrame
    local cameraFocus = camera and camera.Focus
    rootPart.CFrame = CFrame.new(rootPart.Position) * CFrame.Angles(0, spinAngle, 0)
    if camera and cameraCF and cameraFocus then
        local headPart = character:FindFirstChild("Head")
        local inFirstPerson = headPart and (cameraCF.Position - headPart.Position).Magnitude < 1.5
        if inFirstPerson then
            camera.CFrame = cameraCF
            camera.Focus = cameraFocus
        end
    end
end)

local renderBinding = "RETRAC_V25_RENDER"
RunService:BindToRenderStep(renderBinding, Enum.RenderPriority.Camera.Value + 50, function(dt)
    if not active then return end
    updateLocalGun(dt)
    local camera=workspace.CurrentCamera
    if not camera then return end
    updateCameraFOV(camera)
    if spectateTarget then
        if spectateTarget.Parent ~= Players then
            stepSpectate(1)
        else
            local character = spectateTarget.Character
            local pivot = character and (character:FindFirstChild("HumanoidRootPart")
                or character:FindFirstChild("Torso") or character.PrimaryPart)
            if pivot then
                if camera.CameraType ~= Enum.CameraType.Scriptable then
                    camera.CameraType = Enum.CameraType.Scriptable
                end
                local followPosition = (pivot.CFrame * CFrame.new(0, 3.5, 11)).Position
                local lookPosition = pivot.Position + Vector3.new(0, 2, 0)
                local desired = CFrame.lookAt(followPosition, lookPosition)
                camera.CFrame = camera.CFrame:Lerp(desired,
                    1 - math.exp(-math.max(dt,0) * 13))
                camera.Focus = CFrame.new(lookPosition)
            end
        end
    end
    spectateCount.Text = tostring(#availableSpectatePlayers()) .. " available players"

    updateVisuals(camera)
    renderRadarAndArrows(camera)
    local center=viewportMouse(camera)
    circle.Visible=cfg.ShowFOV
    if cfg.ShowFOV then
        local col=FOVColor()
        circle.Position=UDim2.fromOffset(center.X,center.Y)
        circle.Size=UDim2.fromOffset(cfg.FOV*2,cfg.FOV*2)
        circle.BackgroundColor3=col
        circle.BackgroundTransparency=cfg.Filled and (1-cfg.Opacity*0.12) or 1
        circleStroke.Color=col
        circleStroke.Thickness=cfg.Thickness
        circleStroke.Transparency=1-cfg.Opacity
    end

    local aiming=cfg.Aim and not spectateTarget and (cfg.Hold and holding or (not cfg.Hold and toggled))
    if not aiming then
        targetText.Text=""
        resetAimControl()
        return
    end

    local part,player=targetClosestToCursor(camera,center)
    if not part or not player then
        targetText.Text="NO TARGET"
        resetAimControl()
        return
    end

    if aimControl.player~=player then
        resetAimControl()
        aimControl.player=player
    end

    local predicted=aimPosition(part,player.Character,camera)
    local point=camera:WorldToViewportPoint(predicted)
    if point.Z<=0 then return end

    local mouseMove=getMouseMover()
    local useMouse=cfg.MouseLook and mouseMove~=nil
        and canUseMouseLook() and not aimControl.failed

    if useMouse then
        if not calibrateInput(mouseMove,point) then
            targetText.Text="CALIBRATING..."
            return
        end
        useMouse=not aimControl.failed
    end

    if useMouse then
        targetText.Text="TARGET: "..player.DisplayName
        -- Closed-loop proportional control: always measure the current
        -- target error, then send a small mouse delta in the calibrated
        -- direction. Clamp commands to reduce overshoot.
        local current=Vector2.new(point.X,point.Y)
        local error=current-center
        local gain=math.clamp(cfg.Smooth*0.38,0.015,0.32)
        local mx=roundSigned(math.clamp(error.X*gain*aimControl.signX,-16,16))
        local my=roundSigned(math.clamp(error.Y*gain*aimControl.signY,-16,16))
        -- The deadzone prevents jitter when already on target.
        if math.abs(error.X)<1.5 then mx=0 end
        if math.abs(error.Y)<1.5 then my=0 end
        if mx~=0 or my~=0 then
            local ok=pcall(mouseMove,mx,my)
            if not ok then aimControl.failed=true end
        end
    else
        targetText.Text="TARGET: "..player.DisplayName.." (CAM)"
        -- Mouse input unavailable or ineffective: only use camera rotation.
        -- Never run both movement methods in one frame.
        local currentCFrame=camera.CFrame
        local goal=CFrame.lookAt(currentCFrame.Position,predicted)
        local factor=1-math.pow(1-cfg.Smooth,math.clamp(dt*60,0,4))
        camera.CFrame=currentCFrame:Lerp(goal,factor)
    end
end)

local function stop()
    if not active then return end
    active=false
    pcall(function() RunService:UnbindFromRenderStep(renderBinding) end)
    pcall(function() RunService:UnbindFromRenderStep(spinBinding) end)
    releaseSpin()
    pcall(function() RunService:UnbindFromRenderStep(recoilBinding) end)
    if toolActivationConnection then toolActivationConnection:Disconnect() end
    for _,c in ipairs(connections) do pcall(function()c:Disconnect()end) end
    for player in pairs(visuals) do removeVisual(player) end
    restoreGunValues()
    disablePotatoMode()
    stopSpectate()
    for camera, originalFOV in pairs(originalFOVByCamera) do
        pcall(function() camera.FieldOfView = originalFOV end)
    end
    root:Destroy()
    if env.RETRAC_V29_STOP==stop then env.RETRAC_V29_STOP=nil end
end
