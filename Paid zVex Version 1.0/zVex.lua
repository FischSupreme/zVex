-- FPS OPTIMIZER: reversible changes to client-rendered objects only.
-- No instance is destroyed; all modified properties are saved for restoration.
local originalProperties = {}
local optimizerBusy = false
local optimizerConnection = nil
local renderQualityBefore = nil
local fpsStatus = nil
local optimizedCount = 0
local fpsLastApply = 0

local function replaceProperty(instance, prop, value)
    local ok, oldValue = pcall(function() return instance[prop] end)
    if not ok or oldValue == value then return end
    local props = originalProperties[instance]
    if not props then
        props = {}
        originalProperties[instance] = props
    end
    if props[prop] == nil then props[prop] = oldValue end
    pcall(function() instance[prop] = value end)
end

local function ultraLowObject(obj)
    if not cfg.PotatoMode then return end
    -- Never modify Retrac overlays, UI, highlights or player characters.
    -- Optimizing these makes ESP and chams disappear or lose contrast.
    if obj == root or obj:IsDescendantOf(root) then return end
    if obj:IsA("Highlight") or obj:IsA("BillboardGui")
        or obj:IsA("ScreenGui") or obj:IsA("GuiObject") then return end
    for _, player in ipairs(Players:GetPlayers()) do
        local character = player.Character
        if character and (obj == character or obj:IsDescendantOf(character)) then
            return
        end
    end
    if obj:IsA("BasePart") then
        replaceProperty(obj,"Material",Enum.Material.Plastic)
        replaceProperty(obj,"Reflectance",0)
        replaceProperty(obj,"CastShadow",false)
        if obj:IsA("MeshPart") then replaceProperty(obj,"TextureID","") end
    elseif obj:IsA("SpecialMesh") then
        replaceProperty(obj,"TextureId","")
    elseif obj:IsA("Decal") or obj:IsA("Texture") then
        replaceProperty(obj,"Transparency",1)
    elseif obj:IsA("ParticleEmitter") or obj:IsA("Trail")
        or obj:IsA("Beam") or obj:IsA("Fire")
        or obj:IsA("Smoke") or obj:IsA("Sparkles")
        or obj:IsA("PointLight") or obj:IsA("SpotLight")
        or obj:IsA("SurfaceLight") then
        replaceProperty(obj,"Enabled",false)
    elseif obj:IsA("PostEffect") then
        replaceProperty(obj,"Enabled",false)
    elseif obj:IsA("Atmosphere") then
        replaceProperty(obj,"Density",0)
        replaceProperty(obj,"Haze",0)
        replaceProperty(obj,"Glare",0)
    end
    optimizedCount = optimizedCount + 1
end

local function disablePotatoMode()
    cfg.PotatoMode = false
    if optimizerConnection then optimizerConnection:Disconnect() optimizerConnection = nil end
    for instance, props in pairs(originalProperties) do
        if instance and instance.Parent then
            for prop, oldValue in pairs(props) do
                pcall(function() instance[prop] = oldValue end)
            end
        end
        originalProperties[instance] = nil
    end
    if renderQualityBefore then
        pcall(function() settings().Rendering.QualityLevel = renderQualityBefore end)
        renderQualityBefore = nil
    end
    if fpsStatus then fpsStatus.Text = "Normal visuals restored" end
    optimizerBusy = false
end

local function enablePotatoMode()
    if cfg.PotatoMode then return end
    cfg.PotatoMode = true
    optimizedCount = 0
    fpsStatus.Text = "Applying ultra-low graphics..."
    -- Do not force Rendering.QualityLevel to Level01: this can weaken
    -- Highlight/chams outlines even when the GUI itself is untouched.
    -- World materials, textures, particles and lighting are still simplified.
    ultraLowObject(game:GetService("Lighting"))
    replaceProperty(game:GetService("Lighting"),"GlobalShadows",false)
    replaceProperty(game:GetService("Lighting"),"EnvironmentDiffuseScale",0)
    replaceProperty(game:GetService("Lighting"),"EnvironmentSpecularScale",0)
    local terrain = workspace:FindFirstChildOfClass("Terrain")
    if terrain then
        replaceProperty(terrain,"WaterWaveSize",0)
        replaceProperty(terrain,"WaterWaveSpeed",0)
        replaceProperty(terrain,"WaterReflectance",0)
        replaceProperty(terrain,"WaterTransparency",1)
    end
    optimizerConnection = connect(game.DescendantAdded,function(obj)
        if cfg.PotatoMode then
            pcall(ultraLowObject,obj)
        end
    end)
    task.spawn(function()
        local all = game:GetDescendants()
        for i, obj in ipairs(all) do
            if not cfg.PotatoMode or not active then return end
            pcall(ultraLowObject,obj)
            if i % 350 == 0 then task.wait() end
        end
        if cfg.PotatoMode and fpsStatus then
            fpsStatus.Text = "ULTRA LOW ACTIVE • simplified " .. tostring(optimizedCount) .. " objects"
        end
    end)
end

